Import("env")

from datetime import datetime
from gzip import compress
import os
from pathlib import Path
from subprocess import run


project_dir = Path(env["PROJECT_DIR"])
ui_dir = project_dir / "ui"
web_dir = project_dir / "data" / "www"
output = project_dir / "src" / "app" / "embedded_ui.hpp"
version_output = project_dir / "include" / "whisli" / "version.generated.hpp"

# One version for the firmware and the panel it embeds (OTA success is detected by comparing them).
# build_firmware.sh sets it; a plain `pio run` gets one here and passes it on to the UI build.
version = os.environ.get("WHISLI_VERSION") or f"0.002.{datetime.now():%Y%m%d%H%M}"


def cpp_bytes(contents: bytes) -> str:
    return ", ".join(f"0x{byte:02x}" for byte in contents)


run(["npm", "run", "build"], cwd=ui_dir, check=True, env={**os.environ, "WHISLI_VERSION": version})

assets = []
for path in sorted(web_dir.rglob("*")):
    if not path.is_file():
        continue
    relative_path = "/" + path.relative_to(web_dir).as_posix()
    content_type = "text/html; charset=utf-8" if path.suffix == ".html" else (
        "text/css; charset=utf-8" if path.suffix == ".css" else "text/javascript; charset=utf-8"
    )
    assets.append((relative_path, content_type, compress(path.read_bytes(), mtime=0)))

lines = [
    "// Generated by scripts/embed_ui.py. Do not edit manually.",
    "#pragma once",
    "#include <Arduino.h>",
    "namespace whisli::app::embedded_ui {",
    "struct Asset { const char* path; const char* contentType; const uint8_t* bytes; size_t size; };",
]
for index, (_, _, contents) in enumerate(assets):
    lines.append(f"const uint8_t kAsset{index}[] PROGMEM = {{{cpp_bytes(contents)}}};")
lines.append("const Asset kAssets[] = {")
for index, (path, content_type, contents) in enumerate(assets):
    lines.append(f'  {{"{path}", "{content_type}", kAsset{index}, {len(contents)}}},')
lines.extend([
    "};",
    "constexpr size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);",
    "}  // namespace whisli::app::embedded_ui",
    "",
])
output.write_text("\n".join(lines))
version_output.write_text("\n".join([
    "// Generated by scripts/embed_ui.py. Do not edit manually.",
    "#pragma once",
    "namespace whisli {",
    f'constexpr char kFirmwareVersion[] = "{version}";',
    "}  // namespace whisli",
    "",
]))
